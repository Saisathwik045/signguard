"""Synthetic-only Streamlit viewer: no upload widget, URL input, parser or worker authority."""
import base64
import json

import streamlit as st

from signguard.demo import CASES, load_case

st.set_page_config(page_title="SignGuard synthetic demo", page_icon="🛡️", layout="wide")
st.title("SignGuard synthetic demonstration")
st.info("Trusted bundled examples only. Reports were automatically generated by disposable isolated workers. "
        "This viewer cannot accept or analyze your documents.")
case_id = st.selectbox("Synthetic example", list(CASES), format_func=CASES.get)
try:
    result, provenance = load_case(case_id)
except (OSError, ValueError, KeyError):
    st.error("The verified synthetic bundle is unavailable. No analysis fallback is permitted.")
    st.stop()

st.subheader(result["assessment"]["verdict"].replace("_", " ").title())
st.write("Classification: "+result["structure"]["refined_classification"])
st.caption("A mathematically valid signature does not establish trusted identity. Visual candidates and "
           "similarities cannot establish forgery or unauthorized reuse.")
for reason in result["assessment"]["reasons"]:
    st.write(reason)
st.subheader("Actual visual evidence")
columns = st.columns(2)
for index, item in enumerate(result["visual_evidence"]):
    columns[index % 2].image(base64.b64decode(item["base64"]),
                           caption=f"{item['label']} — page {item['page']}")
st.caption("Blue: unverified candidate; red: changed region. Signed snapshots appear where a change was detected.")
with st.expander("Visual differences and revision findings"):
    st.json({"visual_comparisons": result["visual_comparisons"],
             "revision_analysis": result["revision_analysis"],
             "image_forensics": result["image_forensics"]})
st.download_button("Download JSON report", json.dumps(result, indent=2),
                   file_name=f"signguard-demo-{case_id}.json", mime="application/json", on_click="ignore")
st.download_button("Download PDF report", base64.b64decode(result["pdf_report"]["base64"]),
                   file_name=f"signguard-demo-{case_id}.pdf", mime="application/pdf", on_click="ignore")
st.caption("Report shown: "+CASES[case_id])
with st.expander("Synthetic provenance and complete findings"):
    st.json({"provenance": provenance, "report": {k: v for k, v in result.items()
                                                  if k not in {"visual_evidence", "pdf_report"}}})
st.caption("Offline demonstration evidence, not a live production audit receipt or a claim of safe external deployment.")
